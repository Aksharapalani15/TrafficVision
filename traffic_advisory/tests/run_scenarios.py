"""Runs the 13 scenarios and writes docs/TESTING_REPORT.md with ACTUAL results.
Usage (from project folder):  python tests/run_scenarios.py
"""
import datetime
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tests"))
from scenarios import SCENARIOS, check, run_scenario  # noqa: E402


def main():
    out = ["# Testing Report", "",
           f"Generated by `tests/run_scenarios.py` on {datetime.date.today()} (actual execution).", "",
           "**Note:** scenarios use a *fake LLM* (prepared replies) so results are repeatable. "
           "The real Gemini API is not called by automated tests.", ""]
    passed = 0
    for sc in SCENARIOS:
        result, calls = run_scenario(sc)
        problems = check(sc, result)
        passed += not problems
        out += [f"## Scenario {sc['id']}: {sc['name']}", "",
                f"**Status: {'PASS' if not problems else 'FAIL - ' + '; '.join(problems)}**", "",
                f"- LLM mode: `{sc['llm']}` (LLM calls made: {calls})",
                "- Input:", "```json",
                json.dumps({"traffic": sc["traffic"], "prediction": sc["prediction"]}, indent=2), "```",
                f"- Expected: `{json.dumps(sc['expect'])}`",
                "- Actual output:", "```json", json.dumps(result, indent=2), "```", ""]
    out.insert(4, f"**Scenarios passed: {passed}/{len(SCENARIOS)}**\n")
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "--no-header"],
                          cwd=ROOT, capture_output=True, text=True)
    out += ["## Full pytest run", "", "```", proc.stdout.strip(), "```", ""]
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "TESTING_REPORT.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"{passed}/{len(SCENARIOS)} scenarios passed. Report: docs/TESTING_REPORT.md")
    return 0 if passed == len(SCENARIOS) else 1


if __name__ == "__main__":
    sys.exit(main())
